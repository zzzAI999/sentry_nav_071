#!/usr/bin/env python3
"""Validate a saved map pair and atomically select the latest complete run."""

import argparse
import hashlib
import json
import math
import os
from pathlib import Path
import sys
import tempfile

import cv2
import numpy as np
import yaml


def file_hash(path):
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(4 * 1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def pcd_point_count(path):
    fields = {}
    with path.open("rb") as stream:
        while stream.tell() < 65536:
            line = stream.readline()
            if not line:
                raise ValueError("PCD header is incomplete")
            parts = line.decode("ascii").strip().split()
            if not parts or parts[0].startswith("#"):
                continue
            fields[parts[0].upper()] = parts[1:]
            if parts[0].upper() == "DATA":
                break
        else:
            raise ValueError("PCD header is too large")

        names = [name.lower() for name in fields.get("FIELDS", [])]
        sizes = [int(value) for value in fields.get("SIZE", [])]
        counts = [int(value) for value in fields.get("COUNT", ["1"] * len(names))]
        if not {"x", "y", "z"}.issubset(names) or len(sizes) != len(names) or len(counts) != len(names):
            raise ValueError("PCD fields are invalid")
        if any(value <= 0 for value in sizes + counts):
            raise ValueError("PCD field sizes are invalid")
        points = int(fields["POINTS"][0])
        width, height = int(fields["WIDTH"][0]), int(fields["HEIGHT"][0])
        if points <= 0 or width <= 0 or height <= 0 or points != width * height:
            raise ValueError("PCD point count is inconsistent")
        if fields.get("DATA") != ["binary"]:
            raise ValueError("expected binary PCD generated by Point-LIO")
        expected = stream.tell() + points * sum(size * count for size, count in zip(sizes, counts))
        if path.stat().st_size != expected:
            raise ValueError("PCD payload is incomplete")
        return points


def validate_map(yaml_path, pcd_path):
    yaml_path = Path(yaml_path).expanduser().resolve(strict=True)
    pcd_path = Path(pcd_path).expanduser().resolve(strict=True)
    if yaml_path.parent != pcd_path.parent:
        raise ValueError("YAML and PCD must belong to the same mapping directory")
    with yaml_path.open(encoding="utf-8") as stream:
        metadata = yaml.safe_load(stream)
    if not isinstance(metadata, dict):
        raise ValueError("map YAML is not a mapping")
    image_name = metadata.get("image")
    if not isinstance(image_name, str) or Path(image_name).name != image_name:
        raise ValueError("map YAML must reference a local image filename")
    image_path = (yaml_path.parent / image_name).resolve(strict=True)
    if image_path.parent != yaml_path.parent or image_path.suffix.lower() != ".pgm":
        raise ValueError("map image must be a PGM in the mapping directory")
    resolution = float(metadata["resolution"])
    origin = metadata["origin"]
    if (not math.isfinite(resolution) or resolution <= 0 or not isinstance(origin, list)
            or len(origin) < 3 or not all(math.isfinite(float(value)) for value in origin[:3])):
        raise ValueError("map resolution or origin is invalid")
    image = cv2.imread(str(image_path), cv2.IMREAD_GRAYSCALE)
    if image is None or image.size == 0 or np.count_nonzero(image >= 250) < 20:
        raise ValueError("PGM is missing or has fewer than 20 free cells")
    points = pcd_point_count(pcd_path)
    if points < 1000:
        raise ValueError(f"PCD has only {points} points; at least 1000 are required")
    return yaml_path, image_path, pcd_path, points


def record_map(manifest_path, yaml_path, pcd_path):
    yaml_path, image_path, pcd_path, points = validate_map(yaml_path, pcd_path)
    paths = {"yaml": yaml_path, "pgm": image_path, "pcd": pcd_path}
    record = {
        "version": 1,
        "files": {name: {"path": str(path), "size": path.stat().st_size,
                         "sha256": file_hash(path)} for name, path in paths.items()},
        "pcd_points": points,
    }
    manifest_path = Path(manifest_path).expanduser().resolve()
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    temporary = None
    try:
        with tempfile.NamedTemporaryFile("w", encoding="utf-8", dir=manifest_path.parent,
                                         prefix=".latest-", delete=False) as stream:
            temporary = Path(stream.name)
            json.dump(record, stream, indent=2, ensure_ascii=False)
            stream.write("\n")
            stream.flush()
            os.fsync(stream.fileno())
        os.replace(temporary, manifest_path)
    finally:
        if temporary is not None and temporary.exists():
            temporary.unlink()
    return record


def select_map(manifest_path):
    with Path(manifest_path).expanduser().open(encoding="utf-8") as stream:
        record = json.load(stream)
    if record.get("version") != 1 or not isinstance(record.get("files"), dict):
        raise ValueError("unsupported map manifest")
    files = record["files"]
    yaml_path, image_path, pcd_path, _ = validate_map(files["yaml"]["path"], files["pcd"]["path"])
    for name, path in (("yaml", yaml_path), ("pgm", image_path), ("pcd", pcd_path)):
        item = files[name]
        if (str(path) != item["path"] or path.stat().st_size != item["size"]
                or file_hash(path) != item["sha256"]):
            raise ValueError(f"{name} was changed after the map was saved")
    return yaml_path, pcd_path


def main():
    parser = argparse.ArgumentParser()
    commands = parser.add_subparsers(dest="command", required=True)
    record = commands.add_parser("record")
    record.add_argument("--manifest", required=True)
    record.add_argument("--map", required=True)
    record.add_argument("--pcd", required=True)
    select = commands.add_parser("select")
    select.add_argument("--manifest", required=True)
    args = parser.parse_args()
    try:
        if args.command == "record":
            result = record_map(args.manifest, args.map, args.pcd)
            print(f"Saved and selected map: {args.map} ({result['pcd_points']} PCD points)")
        else:
            yaml_path, pcd_path = select_map(args.manifest)
            if any("\n" in str(path) or "\r" in str(path) for path in (yaml_path, pcd_path)):
                raise ValueError("map paths must not contain newlines")
            print(yaml_path)
            print(pcd_path)
    except (OSError, ValueError, KeyError, IndexError, TypeError, yaml.YAMLError) as exc:
        print(f"Map validation failed: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
